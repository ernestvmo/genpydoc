def test_process_changes(filepath, raw_a_filepath, raw_b_filepath, expected):
    with open(filepath) as file:
        diff_text = file.read()
    with open(raw_a_filepath) as a_file:
        a_blob = a_file.read()
    with open(raw_b_filepath) as b_file:
        b_blob = b_file.read()

    results = process_changes(
        changes=parse_diff(diff_text), a_blob=a_blob, b_blob=b_blob
    )
    assert results == expected
