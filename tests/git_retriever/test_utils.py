@pytest.mark.parametrize(
    "filepath, expected",
    [
        (f"{CURR_DIR}/fixtures/cli/cli.py.txt", {"added": 20, "removed": 1}),
        (
            f"{CURR_DIR}/fixtures/commenter/commenter.py.txt",
            {"added": 4, "removed": 1},
        ),
        (f"{CURR_DIR}/fixtures/conf/conf.py.txt", {"added": 0, "removed": 2}),
        (
            f"{CURR_DIR}/fixtures/config/config.py.txt",
            {"added": 23, "removed": 6},
        ),
        (
            f"{CURR_DIR}/fixtures/documenter/documenter.py.txt",
            {"added": 4, "removed": 6},
        ),
        (
            f"{CURR_DIR}/fixtures/git_retriever/git_retriever.py.txt",
            {"added": 29, "removed": 10},
        ),
        (
            f"{CURR_DIR}/fixtures/transformer/transformer.py.txt",
            {"added": 5, "removed": 0},
        ),
        (
            f"{CURR_DIR}/fixtures/utils/utils.py.txt",
            {"added": 16, "removed": 1},
        ),
    ],
)
def test_parse_diff(filepath, expected):
    assert os.path.exists(filepath)

    with open(filepath) as file:
        diff_text = file.read()

    results = parse_diff(diff_text)
    assert isinstance(results, list)
    assert (
        len([res for res in results if res.kind == DiffChangeType.ADD])
        == expected["added"]
    )
    assert (
        len([res for res in results if res.kind == DiffChangeType.REMOVE])
        == expected["removed"]
    )


